// Helper to get unified list of blogs (Master + Custom Admin uploaded blogs)
function getUnifiedBlogs() {
  let custom = [];
  try {
    custom = JSON.parse(localStorage.getItem('custom_blog_items') || '[]');
  } catch (e) {
    custom = [];
  }

  const customIds = new Set(custom.map(c => String(c.id)));
  const baseFiltered = MASTER_BLOGS.filter(d => !customIds.has(String(d.id)));

  return [...custom, ...baseFiltered];
}

if (typeof window !== 'undefined') {
  window.MASTER_BLOGS = MASTER_BLOGS;
  window.getUnifiedBlogs = getUnifiedBlogs;
}
